/**
 * Generates supabase/seed/0002_ops_history.sql from the historical operations
 * report text, using the SAME parser the Telegram bot uses.
 *
 * Why a generator rather than hand-written SQL: the rows that land in the
 * database are then provably identical to what the bot would have produced from
 * the same paste — no second, drifting implementation of the format.
 *
 *   node scripts/generate-ops-seed.mjs
 *
 * The parser is duplicated here only because src/lib/ops-report.ts imports the
 * database client, which a build-time script has no business instantiating.
 * Keep parseOpsReportText below in sync with that file.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/* ── parser (mirror of src/lib/ops-report.ts) ─────────────────────────────── */

function parseDateLabel(raw) {
  const cleaned = raw.trim();
  const range = cleaned.match(/^(\d{1,2})-\d{1,2}\/(\d{1,2})\/(\d{4})$/);
  if (range) {
    const [, day, month, year] = range;
    return { label: cleaned, date: new Date(Date.UTC(+year, +month - 1, +day)) };
  }
  const single = cleaned.match(/^(\d{1,2})\/(\d{1,2})\/(\d{4})$/);
  if (single) {
    const [, day, month, year] = single;
    return { label: cleaned, date: new Date(Date.UTC(+year, +month - 1, +day)) };
  }
  return null;
}

function extractKV(line) {
  const pairs = [];
  const re = /([A-Za-z0-9]+)\s*=\s*([\d.]+)/g;
  let m;
  while ((m = re.exec(line)) !== null) {
    const key = m[1].trim();
    if (!/[A-Za-z]/.test(key)) continue;
    const val = parseFloat(m[2]);
    if (!isNaN(val)) pairs.push([key, val]);
  }
  return pairs;
}

function parseOpsReportText(text) {
  const lines = text.split(/\r?\n/).map((l) => l.trim()).filter(Boolean);
  const entries = new Map();
  let currentLabel = null;
  let section = null;

  for (const line of lines) {
    const dateInfo = parseDateLabel(line);
    if (dateInfo) {
      currentLabel = dateInfo.label;
      if (!entries.has(currentLabel)) {
        entries.set(currentLabel, {
          dateLabel: currentLabel,
          date: dateInfo.date,
          delivered: {}, received: {}, stock: {},
          bags: { kg25: {}, kg40: {} },
        });
      }
      section = null;
      continue;
    }
    if (!currentLabel) continue;
    const entry = entries.get(currentLabel);

    if (/^delivered/i.test(line)) { section = "delivered"; continue; }
    if (/^received/i.test(line)) { section = "received"; continue; }
    if (/^stock/i.test(line)) { section = "stock"; continue; }
    if (/25\s*kg\s*bag/i.test(line)) { section = "bags25"; continue; }
    if (/40\s*kg\s*bag/i.test(line)) { section = "bags40"; continue; }

    const pairs = extractKV(line);
    if (pairs.length === 0 || section === null) continue;
    for (const [key, val] of pairs) {
      if (section === "delivered") entry.delivered[key] = val;
      else if (section === "received") entry.received[key] = val;
      else if (section === "stock") entry.stock[key] = val;
      else if (section === "bags25") entry.bags.kg25[key] = val;
      else if (section === "bags40") entry.bags.kg40[key] = val;
    }
  }

  return Array.from(entries.values()).sort((a, b) => a.date - b.date);
}

/* ── source data ──────────────────────────────────────────────────────────── */

const HISTORICAL_DATA = fs.readFileSync(path.join(ROOT, "scripts", "ops-history.txt"), "utf8");

/* ── emit ─────────────────────────────────────────────────────────────────── */

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const jsonLit = (obj) => `${q(JSON.stringify(obj))}::jsonb`;

const entries = parseOpsReportText(HISTORICAL_DATA);
if (entries.length === 0) {
  console.error("Parsed 0 entries — refusing to write an empty seed.");
  process.exit(1);
}

const out = [];
out.push("-- MinTech Ethiopia — historical daily operations reports.");
out.push("-- GENERATED by scripts/generate-ops-seed.mjs — do not edit by hand.");
out.push("-- Paste into the Supabase SQL editor and Run. Safe to re-run: each day");
out.push("-- upserts on date_label, exactly like the Telegram bot's ingest does.");
out.push(`-- ${entries.length} day-entries, ${entries[0].dateLabel} → ${entries[entries.length - 1].dateLabel}`);
out.push("");
out.push("begin;");
out.push("");

for (const e of entries) {
  const bags = {};
  if (Object.keys(e.bags.kg25).length) bags.kg25 = e.bags.kg25;
  if (Object.keys(e.bags.kg40).length) bags.kg40 = e.bags.kg40;

  out.push(
    `insert into daily_ops_reports (date_label, date, reported_by, delivered, received, stock, bags, raw_text, source) values (\n` +
      `  ${q(e.dateLabel)}, ${q(e.date.toISOString())}, 'historical import',\n` +
      `  ${jsonLit(e.delivered)}, ${jsonLit(e.received)}, ${jsonLit(e.stock)}, ${jsonLit(bags)},\n` +
      `  null, 'app'\n` +
      `) on conflict (date_label) do update set\n` +
      `  delivered = daily_ops_reports.delivered || excluded.delivered,\n` +
      `  received  = daily_ops_reports.received  || excluded.received,\n` +
      `  stock     = daily_ops_reports.stock     || excluded.stock,\n` +
      `  bags = jsonb_build_object(\n` +
      `    'kg25', coalesce(daily_ops_reports.bags -> 'kg25', '{}'::jsonb) || coalesce(excluded.bags -> 'kg25', '{}'::jsonb),\n` +
      `    'kg40', coalesce(daily_ops_reports.bags -> 'kg40', '{}'::jsonb) || coalesce(excluded.bags -> 'kg40', '{}'::jsonb)\n` +
      `  ),\n` +
      `  updated_at = now();`
  );
  out.push("");
}

out.push("commit;");
out.push("");
out.push(`-- Expect: select count(*) from daily_ops_reports;  -->  ${entries.length}`);
out.push("");

const dest = path.join(ROOT, "supabase", "seed", "0002_ops_history.sql");
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, out.join("\n"), "utf8");

const totalDelivered = entries.reduce(
  (a, e) => a + Object.values(e.delivered).reduce((x, y) => x + y, 0), 0);

console.log(`Wrote ${path.relative(ROOT, dest)}`);
console.log(`  ${entries.length} day-entries: ${entries[0].dateLabel} → ${entries[entries.length - 1].dateLabel}`);
console.log(`  total Delivered: ${Math.round(totalDelivered * 1000) / 1000} tonnes`);
